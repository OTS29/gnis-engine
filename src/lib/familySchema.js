// Tables for "Book for family back home". Created automatically the first time the feature is used in test mode.
// site_id is stored as text so it works whatever type sites.id has. GNIS never holds money: family_payments only mirrors the provider.
export const FAMILY_TABLES_LAST = 'family_ratings';

export const FAMILY_SCHEMA = [
  `create table if not exists family_pros (
    site_id text primary key,
    enabled boolean not null default false,
    status text not null default 'pending' check (status in ('pending', 'verified', 'suspended')),
    categories text[] not null default '{}',
    id_method text,
    id_last4 text,
    id_note text not null default '',
    reviewed_by text,
    verified_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now())`,

  `create table if not exists family_bookings (
    id uuid primary key default gen_random_uuid(),
    site_id text not null,
    sender_user_id text not null,
    service_name text not null,
    service_category text not null,
    price_local numeric not null,
    local_currency text not null default 'NGN',
    charge_amount numeric,
    charge_currency text not null default 'NGN',
    platform_fee_percent numeric not null default 0,
    recipient_name text not null,
    recipient_phone text not null,
    recipient_area text not null default '',
    scheduled_date date not null,
    scheduled_time text not null,
    notes text not null default '',
    status text not null default 'requested' check (status in ('requested', 'accepted', 'declined', 'expired', 'payment_pending', 'funds_held', 'in_progress', 'proof_submitted', 'confirmed', 'released', 'disputed', 'refunded', 'cancelled', 'failed')),
    is_test boolean not null default true,
    terms_version text not null default 'draft-1',
    disclosure_accepted_at timestamptz,
    recipient_consent_confirmed boolean not null default false,
    confirmed_by text check (confirmed_by in ('recipient_code', 'sender', 'admin')),
    created_at timestamptz not null default now(),
    accepted_at timestamptz,
    paid_at timestamptz,
    started_at timestamptz,
    proof_submitted_at timestamptz,
    confirmed_at timestamptz,
    released_at timestamptz,
    refunded_at timestamptz,
    respond_by timestamptz)`,
  `create index if not exists family_bookings_site_status on family_bookings (site_id, status)`,
  `create index if not exists family_bookings_sender on family_bookings (sender_user_id)`,

  `create table if not exists family_payments (
    id bigserial primary key,
    booking_id uuid not null references family_bookings (id),
    provider text not null default 'sandbox' check (provider in ('sandbox', 'flutterwave', 'paystack', 'stripe')),
    provider_ref text,
    hold_status text not null default 'none' check (hold_status in ('none', 'held', 'released', 'refunded', 'failed')),
    amount numeric not null,
    currency text not null,
    refund_amount numeric,
    is_test boolean not null default true,
    held_at timestamptz,
    released_at timestamptz,
    refunded_at timestamptz,
    created_at timestamptz not null default now())`,
  `create unique index if not exists family_payments_one_per_booking on family_payments (booking_id)`,

  // The code is stored only as a hash. test_code is filled in test mode only, so a tester can see it on screen.
  `create table if not exists family_codes (
    booking_id uuid primary key references family_bookings (id),
    code_hash text not null,
    test_code text,
    sent_via text check (sent_via in ('sms', 'whatsapp', 'screen_test')),
    sent_at timestamptz,
    expires_at timestamptz not null,
    attempts int not null default 0,
    resend_count int not null default 0,
    locked_at timestamptz,
    used_at timestamptz)`,

  // Photos are kept in the database and shown only through a login-checked address, never a public link.
  `create table if not exists family_proofs (
    id bigserial primary key,
    booking_id uuid not null references family_bookings (id),
    kind text not null check (kind in ('before', 'after')),
    image_b64 text not null,
    sha256 text not null,
    captured_at_claimed timestamptz,
    received_at timestamptz not null default now(),
    lat double precision,
    lng double precision,
    accuracy_m double precision,
    device_note text not null default '')`,
  `create unique index if not exists family_proofs_one_kind on family_proofs (booking_id, kind)`,
  `create unique index if not exists family_proofs_sha on family_proofs (sha256)`,

  `create table if not exists family_events (
    id bigserial primary key,
    booking_id uuid not null references family_bookings (id),
    actor_type text not null check (actor_type in ('sender', 'pro', 'recipient', 'admin', 'system', 'provider')),
    actor_id text,
    event text not null,
    detail jsonb not null default '{}',
    at timestamptz not null default now())`,
  `create index if not exists family_events_booking on family_events (booking_id, at)`,

  `create table if not exists family_disputes (
    id bigserial primary key,
    booking_id uuid not null references family_bookings (id),
    opened_by text not null,
    reason text not null,
    details text not null default '',
    after_release boolean not null default false,
    status text not null default 'open' check (status in ('open', 'resolved_refund', 'resolved_release', 'resolved_split')),
    refund_amount numeric,
    resolution_note text,
    resolved_by text,
    opened_at timestamptz not null default now(),
    resolved_at timestamptz)`,
  `create index if not exists family_disputes_booking on family_disputes (booking_id)`,

  `create table if not exists family_ratings (
    booking_id uuid primary key references family_bookings (id),
    rating int not null check (rating between 1 and 5),
    comment text not null default '',
    created_at timestamptz not null default now())`,
];
